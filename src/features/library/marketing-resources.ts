/**
 * Biblioteca de recursos de marketing.
 *
 * O catálogo vive em código, e não no banco, de propósito: é conteúdo curado
 * que muda poucas vezes por ano, precisa de revisão antes de entrar (licença
 * errada aqui vira problema jurídico lá na frente) e não tem dono por empresa.
 * Virar tabela exigiria tela de administração, permissão e auditoria para um
 * dado que o time inteiro só lê.
 *
 * ## A regra que organiza tudo
 *
 * O campo mais importante NÃO é o preço, é a `licenca`. Quem está montando uma
 * peça com pressa precisa saber, em uma olhada, se pode usar aquilo num anúncio
 * pago e se precisa creditar alguém. Baixar um arquivo CC BY e publicar sem o
 * crédito é a falha mais comum e a mais cara.
 *
 * Por isso a licença é um enum fechado, e não texto livre.
 */

export type Categoria =
  | 'video'
  | 'imagem'
  | 'musica'
  | 'motion'
  | 'apresentacao'
  | 'mockup'
  | 'ilustracao'
  | 'icones'
  | 'cor'
  | 'utilitario'
  | 'quadro'
  | '3d'
  | 'edicao'
  | 'site'
  | 'ia'

/**
 * O que a pessoa precisa saber ANTES de baixar.
 *
 * - `livre`: uso comercial liberado e sem obrigação de crédito. É o caminho
 *   seguro, e o que a busca favorece.
 * - `credito`: uso comercial liberado, MAS exige citar o autor no material
 *   final. Esquecer disso é violação de licença.
 * - `misto`: o acervo tem itens dos dois tipos; a licença é por item e precisa
 *   ser conferida na hora de baixar.
 * - `assinatura`: liberado enquanto a assinatura estiver ativa. Atenção ao que
 *   vale para o material já publicado depois do cancelamento.
 * - `porItem`: cada peça é comprada com a própria licença.
 */
export type Licenca = 'livre' | 'credito' | 'misto' | 'assinatura' | 'porItem'

/** `1` é o que abrir primeiro: resolve a maior parte do trabalho. */
export type Tier = 1 | 2

export interface Recurso {
  nome: string
  url: string
  categoria: Categoria
  tier: Tier
  licenca: Licenca
  /** Preço em uma linha, do jeito que a pessoa precisa ler. */
  preco: string
  /** Para que serve, em uma frase útil na hora de escolher. */
  paraQue: string
  forte: string
  fraco: string
  /** Aviso que aparece destacado no cartão quando há risco ou pegadinha. */
  atencao?: string
}

