const { chromium } = require('playwright-core')
const fs = require('fs')
;(async () => {
  const seed = JSON.parse(fs.readFileSync('seed-out.json'))
  const t = (await (await fetch('http://127.0.0.1:3599/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'nicolas@nevo.test', password: 'nevo1234' }) })).json()).accessToken
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const c = await b.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  await c.addInitScript(([t, co]) => { localStorage.setItem('token', t); localStorage.setItem('activeCompany', co); localStorage.setItem('onboarding.completed', '1'); localStorage.setItem('onboarding.autoShown', '1'); localStorage.setItem('ui.idlePermissionPrompt', 'done'); localStorage.setItem('ui.theme', 'light') }, [t, seed.companies.pet])
  const p = await c.newPage()
  await p.goto('http://localhost:5174/')
  await p.addStyleTag({ content: '#__vue-devtools-container__{display:none!important}' })
  await p.waitForTimeout(3000)
  await p.tap('button.m-tab[aria-haspopup="dialog"]')
  await p.waitForTimeout(600)
  const open = await p.evaluate(() => ({ dialog: !!document.querySelector('[role=dialog][aria-modal=true]'), focus: document.activeElement?.getAttribute('aria-label') }))
  await p.screenshot({ path: 'sheet-open.png' })
  await p.keyboard.press('Escape')
  await p.waitForTimeout(500)
  const closed = await p.evaluate(() => ({ dialog: !!document.querySelector('.more-sheet'), focus: document.activeElement?.className }))
  console.log('aberto:', JSON.stringify(open), '| depois do Esc:', JSON.stringify(closed))
  await b.close()
})()
