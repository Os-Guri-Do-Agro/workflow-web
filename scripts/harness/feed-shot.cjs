const { chromium } = require('playwright-core')
const fs = require('fs')
;(async () => {
  const seed = JSON.parse(fs.readFileSync(__dirname + '/seed-out.json'))
  const t = (await (await fetch('http://127.0.0.1:3599/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'nicolas@nevo.test', password: 'nevo1234' }) })).json()).accessToken
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const c = await b.newContext({ viewport: { width: 1440, height: 1300 } })
  await c.addInitScript(([t, co]) => { localStorage.setItem('token', t); localStorage.setItem('activeCompany', co); localStorage.setItem('onboarding.completed', '1'); localStorage.setItem('onboarding.autoShown', '1'); localStorage.setItem('ui.idlePermissionPrompt', 'done'); localStorage.setItem('ui.theme', 'light'); localStorage.setItem('dashboard.tab', 'panel') }, [t, seed.companies.pet])
  const p = await c.newPage()
  const errs = []; p.on('pageerror', (e) => errs.push(e.message))
  await p.goto('http://localhost:5174/')
  await p.addStyleTag({ content: '#__vue-devtools-container__{display:none!important}' })
  await p.waitForTimeout(2500)
  await p.mouse.wheel(0, 900); await p.waitForTimeout(2500)
  const feed = p.locator('.dash-feed-slot')
  if (await feed.count()) await feed.screenshot({ path: __dirname + '/feed-deploy.png' })
  await p.click('button[aria-label*="otifica"], .inbox-bell button, button:has(.lucide-bell)').catch(() => {})
  await p.waitForTimeout(1200)
  await p.screenshot({ path: __dirname + '/inbox-deploy.png', clip: { x: 900, y: 0, width: 540, height: 700 } })
  console.log('erros:', errs.length ? errs.join(' | ') : 'nenhum')
  await b.close()
})()
