const { chromium } = require('playwright-core')
const fs = require('fs')
;(async () => {
  const seed = JSON.parse(fs.readFileSync('seed-out.json'))
  const t = (await (await fetch('http://127.0.0.1:3599/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'nicolas@nevo.test', password: 'nevo1234' }) })).json()).accessToken
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const c = await b.newContext({ viewport: { width: 1440, height: 1000 } })
  await c.addInitScript(([t, co, font]) => { localStorage.setItem('token', t); localStorage.setItem('activeCompany', co); localStorage.setItem('onboarding.completed', '1'); localStorage.setItem('onboarding.autoShown', '1'); localStorage.setItem('ui.idlePermissionPrompt', 'done'); localStorage.setItem('ui.font', font) }, [t, seed.companies.pet, process.argv[2] || 'figtree'])
  const p = await c.newPage()
  await p.goto('http://localhost:5174/settings#aparencia')
  await p.addStyleTag({ content: '#__vue-devtools-container__{display:none!important}' })
  await p.waitForTimeout(3500)
  const ff = await p.evaluate(() => getComputedStyle(document.body).fontFamily)
  console.log('body font:', ff.slice(0, 80))
  const el = await p.$('.font-options')
  if (el) await el.scrollIntoViewIfNeeded()
  await p.screenshot({ path: `font-${process.argv[2] || 'figtree'}.png` })
  await p.goto('http://localhost:5174/board'); await p.addStyleTag({ content: '#__vue-devtools-container__{display:none!important}' }); await p.waitForTimeout(3500)
  await p.screenshot({ path: `font-board-${process.argv[2] || 'figtree'}.png` })
  await b.close()
})()
