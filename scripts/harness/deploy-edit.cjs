const { chromium } = require('playwright-core')
const fs = require('fs')
;(async () => {
  const seed = JSON.parse(fs.readFileSync(__dirname + '/seed-out.json'))
  const t = (await (await fetch('http://127.0.0.1:3599/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'nicolas@nevo.test', password: 'nevo1234' }) })).json()).accessToken
  const auth = { Authorization: 'Bearer ' + t, 'x-company-id': seed.companies.pet }
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const c = await b.newContext({ viewport: { width: 1440, height: 1100 } })
  await c.addInitScript(([t, co]) => { localStorage.setItem('token', t); localStorage.setItem('activeCompany', co); localStorage.setItem('onboarding.completed', '1'); localStorage.setItem('onboarding.autoShown', '1'); localStorage.setItem('ui.idlePermissionPrompt', 'done'); localStorage.setItem('ui.theme', 'light') }, [t, seed.companies.pet])
  const p = await c.newPage()
  await p.goto('http://localhost:5174/settings#deploys')
  await p.addStyleTag({ content: '#__vue-devtools-container__{display:none!important}' })
  await p.waitForTimeout(3000)
  await p.click('.dep-item button:has-text("Editar")')
  await p.waitForTimeout(600)
  const providerDisabled = await p.locator('.dep-form [data-disabled], .dep-form button[disabled]').count()
  await p.fill('input[placeholder^="Ex.: App PetJourney"]', 'App PetJourney (produção) v2')
  const ta = p.locator('textarea.dep-textarea')
  await ta.fill((await ta.inputValue()) + '\nd3novoapp Painel admin')
  await p.screenshot({ path: __dirname + '/deploy-5-edit.png' })
  await p.click('.dep-form button[type=submit]')
  await p.waitForTimeout(1500)
  const list = await (await fetch('http://127.0.0.1:3599/deploy-integrations', { headers: auth })).json()
  const it = list.find((x) => x.name === 'App PetJourney (produção) v2')
  console.log('provedor travado na edição:', providerDisabled > 0)
  console.log('salvou nome:', !!it, '| apps:', it?.allowedSources.map((s) => s.id + (s.label ? ` (${s.label})` : '')).join(', '))
  console.log('form fechou:', (await p.locator('.dep-form').count()) === 0)
  await b.close()
})()
